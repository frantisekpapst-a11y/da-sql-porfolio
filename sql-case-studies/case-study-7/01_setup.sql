MALÁ ANALÝZA OBJEDNÁVEK A TRŽEB — zadání a vstupní dataset
Data jsou syntetická, nevypovídají o skutečné firmě ani zákaznících.

Zadavatel: obchodní vedoucí firmy s B2B a B2C zákazníky.
Cíl: vyhodnotit rok 2025 a identifikovat hlavní zákazníky.
Otázky:
1. Jak se vyvíjí měsíční počet objednávek a tržby? (CTE, LAG)
