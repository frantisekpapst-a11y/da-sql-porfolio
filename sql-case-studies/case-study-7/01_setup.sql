Rozsah: kontrola a čištění v SQL, hlavní EDA v SQL, analytické view,
načtení view přes Power Query do Excelu, grafy a popisná statistika.
Power Pivot není potřeba. Řešení analytických dotazů tento soubor neobsahuje.

Tabulky a sloupce:
customers_raw: customer_id (ID), customer_name (název),
              customer_type (B2B/B2C), region (region).
orders_raw: raw_row_id (technické ID importovaného řádku),
            order_id (číslo objednávky), order_date (datum),
            customer_id (ID zákazníka), order_amount (hodnota v Kč).
Jeden obchodní záznam = jedna celá objednávka, nikoli položka.
