Neřešíme náklady, zisk, marži, storna ani vratky.

Vstup: 80 zákazníků, 1 000 odlišných čísel objednávek + 5 duplicitních
kopií = 1 005 importovaných řádků. Záznamy nejsou chronologicky seřazené.
Dataset obsahuje několik chybějících hodnot, mezer v textu,
neplatnou hodnotu objednávky a odkazy na neznámého zákazníka.
Chyby budeme hledat a o způsobu zpracování rozhodovat společně.
Původní tabulky *_raw zachováme jako vstupní zdroj.

Spuštění: SSMS, připojení (localdb)\DataAnalyticsLocalDB,
databáze sales_analysis_practice, Execute / F5.
Skript vytvoří pouze dvě níže pojmenované tabulky a vloží data.
Pokud některá již existuje, skončí bez přepsání.
*/

